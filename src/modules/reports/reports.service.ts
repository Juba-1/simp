import {
  Injectable,
  NotFoundException,
  BadRequestException,
} from '@nestjs/common';
import { FormInstanceStatus, IpcStatus } from '@prisma/client';
import { PrismaService } from '../../database/prisma.service';
import { TenantScopeService } from '../../common/services/tenant-scope.service';
import { AuthenticatedUser } from '../../common/interfaces/authenticated-user.interface';
import { PdfGeneratorService } from './pdf-generator.service';

@Injectable()
export class ReportsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly tenantScope: TenantScopeService,
    private readonly pdf: PdfGeneratorService,
  ) {}

  async generateFormInstancePdf(
    user: AuthenticatedUser,
    formInstanceId: string,
  ): Promise<{ buffer: Buffer; filename: string }> {
    await this.tenantScope.assertClientAdmin(user);

    const form = await this.prisma.formInstance.findFirst({
      where: { id: formInstanceId, deletedAt: null },
      include: {
        template: true,
        project: { select: { id: true, name: true, code: true } },
        createdBy: {
          select: { firstName: true, lastName: true, email: true },
        },
        approvalRecords: { orderBy: { createdAt: 'asc' }, take: 20 },
      },
    });

    if (!form) {
      throw new NotFoundException('Form instance not found');
    }

    await this.tenantScope.assertClientProjectAccess(user, form.projectId);

    if (form.status !== FormInstanceStatus.APPROVED) {
      throw new BadRequestException(
        'Only approved forms can be exported to PDF',
      );
    }

    const buffer = await this.pdf.createBuffer((doc) => {
      this.pdf.drawHeader(
        doc,
        `${form.template.code} — ${form.template.name}`,
        `Project: ${form.project.name} (${form.project.code})`,
      );

      this.pdf.drawKeyValue(doc, 'Reference', form.referenceNumber ?? form.id);
      this.pdf.drawKeyValue(doc, 'Status', form.status);
      this.pdf.drawKeyValue(
        doc,
        'Submitted By',
        `${form.createdBy.firstName} ${form.createdBy.lastName}`,
      );
      this.pdf.drawKeyValue(doc, 'Comments', form.comments || '—');
      this.pdf.drawKeyValue(
        doc,
        'Device Timestamp',
        form.deviceTimestamp.toISOString(),
      );

      if (form.liabilityShiftRedAlert) {
        doc.moveDown(0.5);
        doc.fillColor('#cc0000').font('Helvetica-Bold').text(
          '⚠ LIABILITY SHIFT RED ALERT — Consultant investigation required',
        );
        doc.fillColor('#000000');
      }

      this.pdf.drawJsonSection(
        doc,
        'Form Data (JSONB Payload)',
        form.data as Record<string, unknown>,
      );

      if (form.approvalRecords.length > 0) {
        doc.moveDown();
        doc.fontSize(12).font('Helvetica-Bold').text('Approval Trail');
        doc.moveDown(0.3);
        for (const record of form.approvalRecords) {
          doc
            .fontSize(9)
            .font('Helvetica')
            .text(
              `${record.createdAt.toISOString()} — ${record.action}: ${record.fromStatus} → ${record.toStatus}`,
            );
        }
      }

      doc.moveDown(2);
      doc
        .fontSize(8)
        .fillColor('#888888')
        .text(
          `Generated by SIMP Platform on ${new Date().toISOString()} | Document ID: ${form.id}`,
          { align: 'center' },
        );
    });

    const filename = `${form.template.code}-${form.referenceNumber ?? form.id}.pdf`;
    return { buffer, filename };
  }

  async generateIpcPdf(
    user: AuthenticatedUser,
    ipcId: string,
  ): Promise<{ buffer: Buffer; filename: string }> {
    await this.tenantScope.assertClientAdmin(user);

    const ipc = await this.prisma.interimPaymentCertificate.findFirst({
      where: { id: ipcId, deletedAt: null },
      include: {
        project: { select: { id: true, name: true, code: true } },
        contractorOrg: { select: { name: true, type: true } },
        lineItems: {
          orderBy: { sortOrder: 'asc' },
          include: {
            formInstance: {
              select: { referenceNumber: true, id: true },
            },
          },
        },
      },
    });

    if (!ipc) {
      throw new NotFoundException('IPC not found');
    }

    await this.tenantScope.assertClientProjectAccess(user, ipc.projectId);

    if (ipc.status !== IpcStatus.APPROVED) {
      throw new BadRequestException(
        'Only approved IPCs can be exported to PDF',
      );
    }

    const buffer = await this.pdf.createBuffer((doc) => {
      this.pdf.drawHeader(
        doc,
        `Interim Payment Certificate`,
        `${ipc.certificateNumber} | ${ipc.project.name}`,
      );

      this.pdf.drawKeyValue(doc, 'Contractor', ipc.contractorOrg.name);
      this.pdf.drawKeyValue(doc, 'Status', ipc.status);
      this.pdf.drawKeyValue(doc, 'Currency', ipc.currency);
      this.pdf.drawKeyValue(
        doc,
        'Subtotal',
        `${ipc.subtotalAmount.toString()} ${ipc.currency}`,
      );
      if (ipc.periodStart) {
        this.pdf.drawKeyValue(
          doc,
          'Period',
          `${ipc.periodStart.toISOString().slice(0, 10)} — ${ipc.periodEnd?.toISOString().slice(0, 10) ?? '—'}`,
        );
      }

      doc.moveDown();
      doc.fontSize(12).font('Helvetica-Bold').text('Line Items (Approved WIRs)');
      doc.moveDown(0.3);

      const tableTop = doc.y;
      doc.fontSize(9).font('Helvetica-Bold');
      doc.text('WIR Ref', 50, tableTop, { width: 80 });
      doc.text('Description', 140, tableTop, { width: 160 });
      doc.text('Qty', 310, tableTop, { width: 40 });
      doc.text('Rate', 355, tableTop, { width: 60 });
      doc.text('Amount', 420, tableTop, { width: 80 });
      doc.moveDown();

      let y = doc.y;
      doc.font('Helvetica');
      for (const item of ipc.lineItems) {
        if (y > doc.page.height - 80) {
          doc.addPage();
          y = 50;
        }
        doc.text(item.formInstance.referenceNumber ?? item.formInstance.id, 50, y, {
          width: 80,
        });
        doc.text(item.description, 140, y, { width: 160 });
        doc.text(item.quantity.toString(), 310, y, { width: 40 });
        doc.text(item.unitRate.toString(), 355, y, { width: 60 });
        doc.text(item.lineAmount.toString(), 420, y, { width: 80 });
        y += 18;
        doc.y = y;
      }

      doc.moveDown();
      doc.font('Helvetica-Bold').text(
        `Total: ${ipc.subtotalAmount.toString()} ${ipc.currency}`,
        { align: 'right' },
      );

      doc.moveDown(2);
      doc
        .fontSize(8)
        .fillColor('#888888')
        .text(
          `Generated by SIMP Platform on ${new Date().toISOString()} | IPC ID: ${ipc.id}`,
          { align: 'center' },
        );
    });

    return { buffer, filename: `${ipc.certificateNumber}.pdf` };
  }
}
